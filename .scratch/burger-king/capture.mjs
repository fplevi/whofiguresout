import { createRequire } from 'module';
const require = createRequire('D:/Projetos/BurguerKingNewSite/prototype/package.json');
const { chromium } = require('@playwright/test');
const out = 'D:/Projetos/Portfolio/.scratch/burger-king/captures/';
const base = 'https://fplevi.github.io/BurguerKingDelivery/';
const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
await page.goto(base); await page.waitForTimeout(4000);
await page.screenshot({ path: out + 'menu-visitor.png' });
const hero = page.locator('section.hero');
await hero.getByRole('button', { name: 'Informar endereço de entrega' }).click();
await page.waitForTimeout(800);
await page.screenshot({ path: out + 'address-visitor.png' });
const search = page.getByRole('searchbox').or(page.getByRole('textbox')).first();
await search.click(); await page.waitForTimeout(500);
await page.screenshot({ path: out + 'address-search-open.png' });
await page.keyboard.type('paulista'); await page.waitForTimeout(800);
await page.screenshot({ path: out + 'address-search.png' });
await page.getByText('Avenida Paulista, 1578').first().click(); await page.waitForTimeout(1500);
await page.screenshot({ path: out + 'address-confirm.png' });
await browser.close();
